"""Gated five-page Decision Context Benchmark paper authoring.

No prose, numerical conclusions or PDF is generated by importing this module.
The owner/executor authors a final five-page narrative only after terminal checks.
Numeric prose uses {{claim_id}} references into checked analysis/table JSON. A
claim is {source: 'tables'|'analysis', path: [...], value: number, format: ...,
population: 'browsesafe'|another_source|'protocol'|'study'|'accounting'}.

Pages have fixed scientific roles and blocks of paragraph, heading, table, figure
or references. Figures are approved PNG artifacts, hash-bound to checked tables.
Citation tokens {{cite:ID}} resolve human-readable structured references. Free
numeric prose, stale claims, placeholders and incomplete provenance are rejected.

Immediately before the first actual PDF creation the executor must run the PDF
skill's authoring marker. That marker is intentionally outside this library.
Rendering dependencies are lazy; schema/gate tests create no PDF and need stdlib.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
import re
import sys
import tempfile
from pathlib import Path
from urllib.parse import urlparse
from xml.sax.saxutils import escape

VERSION = 'v6-paper-narrative-1'
TABLES_VERSION = 'v6-aggregate-tables-1'
PROJECT = 'Decision Context Benchmark'
ROLES = ('question_and_context', 'data_and_methods', 'primary_results',
         'source_diagnostics', 'discussion_and_references')
SOURCES = {'browsesafe', 'aib', 'nvidia', 'spml', 'infuse', 'scope'}
REQUIRED_CHECKS = ('analysis_recomputed', 'terminal_execution_verified', 'accounting_verified',
                   'label_provenance_verified', 'freeze_verified', 'narrative_verified')
PROVENANCE = {'labels': 'agent_reviewed_source_agreement',
              'browsesafe': 'privacy_rewritten_training_release',
              'nvidia': 'synthetic_success_selected_local_deletion_controls',
              'construct': 'static_detection_and_scope_diagnostics'}
TOKEN = re.compile(r'\{\{([A-Za-z][A-Za-z0-9_:-]*)\}\}')
PLACEHOLDER = re.compile(r'\b(?:TODO|TBD|PLACEHOLDER|FIXME)\b|lorem ipsum|\?\?+', re.I)
ASCII_DASHES = re.compile('[\u2010-\u2015\u2212]')


def digest(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                     separators=(',', ':'), allow_nan=False).encode()).hexdigest()


def file_digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def resolve(document, path):
    """Resolve a structured JSON path with no expressions, wildcard or evaluation."""
    if not isinstance(path, list) or not path:
        raise ValueError('Claim paths must be nonempty explicit JSON paths')
    value, population = document, None
    for part in path:
        if isinstance(value, dict):
            if value.get('source') in SOURCES:
                population = value['source']
            if type(part) is not str or part not in value:
                raise ValueError('Missing checked claim path')
        elif isinstance(value, list):
            if type(part) is not int or not 0 <= part < len(value):
                raise ValueError('Invalid checked array index')
        else:
            raise ValueError('Claim path continues past a JSON scalar')
        value = value[part]
    return value, population


def number(value):
    return type(value) in (int, float) and math.isfinite(value)


def format_claim(value, specification):
    if specification == 'literal':
        if not isinstance(value, str) or not value.strip() or TOKEN.search(value):
            raise ValueError('A checked route/revision literal must be a nonempty terminal string')
        _plain(value, numbers=True)
        return value
    if specification == 'integer':
        if not number(value) or value != int(value):
            raise ValueError('Integer claim requires an integral checked value')
        return f'{int(value):,}'
    if not number(value):
        raise ValueError('Numerical claims require a finite checked value')
    if specification == 'p':
        if not 0 <= value <= 1:
            raise ValueError('A p value must be between zero and one')
        return f'{value:.3g}'
    match = re.fullmatch(r'(decimal|percent|pp|usd)([0-6])', specification or '')
    if not match:
        raise ValueError('Unknown numerical claim display format')
    kind, places = match.group(1), int(match.group(2))
    if kind == 'percent':
        if not 0 <= value <= 1:
            raise ValueError('Percent format requires a checked fraction')
        return f'{value * 100:.{places}f}%'
    if kind == 'pp':
        # Checked tables already use percentage-point units in *_pp columns.
        return f'{value:.{places}f} pp'
    if kind == 'usd':
        if value < 0:
            raise ValueError('Cost claims cannot be negative')
        return f'US${value:.{places}f}'
    return f'{value:.{places}f}'


def _plain(text, *, numbers=False):
    if not isinstance(text, str) or not text.strip():
        raise ValueError('Authored text must be nonempty')
    if PLACEHOLDER.search(text):
        raise ValueError('Unchecked narrative placeholder')
    if ASCII_DASHES.search(text):
        raise ValueError('Use ASCII hyphens in the paper source')
    stripped = TOKEN.sub('', text)
    if '{{' in stripped or '}}' in stripped:
        raise ValueError('Malformed or unresolved narrative token')
    if not numbers and re.search(r'\d', stripped):
        raise ValueError('Numerical prose must reference the checked claim ledger')
    return text


def validate(narrative, analysis, tables, verification, *, base_dir=None):
    """Validate evidence and final authored source, without importing a PDF writer."""
    if narrative.get('version') != VERSION or analysis.get('version') != 'v6-analysis-1' or tables.get('version') != TABLES_VERSION:
        raise ValueError('Unsupported paper/evidence schema')
    if tables.get('analysis_set') != 'first_attempt_primary' or analysis.get('analysis_set') != 'first_attempt_primary':
        raise PermissionError('The primary paper cannot silently substitute recovered outcomes')
    if not tables.get('empirical_checks_complete') or not tables.get('review_resolution_complete'):
        raise PermissionError('Final empirical checks and final label admission must be complete')
    if not all(verification.get(field) is True for field in REQUIRED_CHECKS):
        raise PermissionError('Paper verification gates are incomplete')
    for name, value in (('analysis', analysis), ('tables', tables), ('narrative', narrative)):
        if verification.get(name + '_sha256') != digest(value):
            raise ValueError('Checked ' + name + ' hash changed')
    if tables.get('analysis_sha256') != digest(analysis):
        raise ValueError('Tables do not derive from this checked analysis')
    if analysis.get('observed_cells', 0) <= 0 or tables.get('observed_cells') != analysis['observed_cells']:
        raise PermissionError('An unrun scaffold cannot become an empirical paper')
    if narrative.get('provenance') != PROVENANCE:
        raise ValueError('Required label/source/construct provenance is missing or changed')
    title = _plain(narrative.get('title'))
    if PROJECT not in title or 'SLM Benchmark' in title:
        raise ValueError('Use the Decision Context Benchmark project name')
    authors = narrative.get('authors', '')
    if authors:
        _plain(authors)
    references = {}
    for reference in narrative.get('references', []):
        identity = reference.get('id')
        if not isinstance(identity, str) or not re.fullmatch('[A-Za-z][A-Za-z_-]*', identity) or identity in references:
            raise ValueError('Reference IDs must be unique readable labels')
        for field in ('authors', 'title'):
            _plain(reference.get(field), numbers=True)
            if TOKEN.search(reference[field]):
                raise ValueError('Bibliographic metadata cannot contain unresolved tokens')
        url = urlparse(reference.get('url', ''))
        if url.scheme != 'https' or not url.netloc or url.username or url.password:
            raise ValueError('References require usable HTTPS source links')
        if type(reference.get('year')) is not int or not 1800 <= reference['year'] <= 2100:
            raise ValueError('References require a bibliographic year')
        references[identity] = reference
    if not references:
        raise ValueError('The paper requires checked primary references')
    claims = narrative.get('claims')
    if not isinstance(claims, dict):
        raise ValueError('A structured numeric claim ledger is required')
    rendered_claims, claim_receipts = {}, {}
    for identity, claim in claims.items():
        if not re.fullmatch('[A-Za-z][A-Za-z0-9_]*', identity):
            raise ValueError('Invalid claim ID')
        source = claim.get('source')
        if source not in ('analysis', 'tables'):
            raise ValueError('Numerical claims require checked analysis or table evidence')
        value, population = resolve(analysis if source == 'analysis' else tables, claim.get('path'))
        literal = claim.get('format') == 'literal'
        if literal and (claim['path'][0] not in ('route_metadata', 'source_revisions') or not isinstance(value, str)):
            raise ValueError('Checked literals are restricted to route metadata or source revisions')
        if (not literal and (not number(value) or not number(claim.get('value')))) or value != claim['value']:
            raise ValueError('Unchecked/stale/null numerical claim: ' + identity)
        declared = claim.get('population')
        if population is not None:
            if declared != population:
                raise ValueError('Main/secondary source population mismatch in claim: ' + identity)
        elif declared == 'protocol':
            if claim['path'][0] != 'analysis_plan':
                raise ValueError('Methodological numbers must reference the checked analysis plan')
        elif declared == 'accounting':
            if source != 'tables' or claim['path'][0] != 'accounting':
                raise ValueError('Accounting claims require a checked accounting table')
        elif declared != 'study':
            raise ValueError('Numeric claim lacks a clear source or study population')
        display = format_claim(value, claim.get('format'))
        rendered_claims[identity] = display
        claim_receipts[identity] = {'source': source, 'path': claim['path'], 'value': value,
                                   'population': declared, 'format': claim['format'], 'display': display}
    used_claims, used_references, used_figures = set(), set(), set()

    def text(value):
        _plain(value)
        for match in TOKEN.finditer(value):
            identity = match.group(1)
            if identity.startswith('cite:'):
                reference = identity[5:]
                if reference not in references:
                    raise ValueError('Unresolved citation token')
                used_references.add(reference)
            else:
                if identity not in claims:
                    raise ValueError('Unresolved numeric claim token')
                used_claims.add(identity)
        return value

    text(title)
    pages = narrative.get('pages')
    if not isinstance(pages, list) or len(pages) != 5 or [page.get('role') for page in pages] != list(ROLES):
        raise ValueError('The final paper requires the five ordered scientific page roles')
    figure_receipts = verification.get('figure_artifacts', {})
    checked_figures = {}
    base = Path(base_dir or '.').resolve()
    for page in pages:
        text(page.get('heading'))
        blocks = page.get('blocks')
        if not isinstance(blocks, list) or not blocks or not any(block.get('type') == 'paragraph' for block in blocks):
            raise ValueError('Each page requires authored narrative paragraphs')
        for block in blocks:
            kind = block.get('type')
            if kind in ('paragraph', 'heading'):
                text(block.get('text'))
            elif kind == 'table':
                text(block.get('caption'))
                values = block.get('rows')
                if not isinstance(values, list) or len(values) < 2 or len(values) > 18:
                    raise ValueError('Paper tables require bounded readable rows')
                width = len(values[0])
                if not 2 <= width <= 6 or any(not isinstance(row, list) or len(row) != width for row in values):
                    raise ValueError('Paper tables must be rectangular with readable columns')
                for row in values:
                    for value in row:
                        text(value)
            elif kind == 'figure':
                identity = block.get('figure')
                if identity in used_figures or identity not in figure_receipts:
                    raise ValueError('Paper figures must be uniquely approved artifacts')
                receipt = figure_receipts[identity]
                path = Path(receipt.get('path', ''))
                path = path if path.is_absolute() else base / path
                if (receipt.get('visually_verified') is not True or receipt.get('tables_sha256') != digest(tables)
                        or path.suffix.lower() != '.png' or not path.is_file()
                        or file_digest(path) != receipt.get('sha256')):
                    raise ValueError('Figure hash, table binding or visual verification changed')
                text(block.get('caption'))
                used_figures.add(identity)
                checked_figures[identity] = {'path': str(path.resolve()), 'sha256': receipt['sha256']}
            elif kind == 'references':
                if page['role'] != ROLES[-1]:
                    raise ValueError('References belong on the final paper page')
            else:
                raise ValueError('Unknown authored paper block')
    if used_claims != set(claims):
        raise ValueError('Unused claim ledger entries must be removed or cited')
    if not used_references or not any(block.get('type') == 'references' for block in pages[-1]['blocks']):
        raise ValueError('Use source citations and render references on the final page')
    return {'version': 'v6-paper-validation-1', 'project': PROJECT, 'page_count': 5,
            'analysis_sha256': digest(analysis), 'tables_sha256': digest(tables),
            'narrative_sha256': digest(narrative), 'claim_ledger': claim_receipts,
            'used_reference_ids': sorted(used_references), 'figures': checked_figures,
            'pdf_created': False}


def _render_text(text, narrative, validation):
    def substitute(match):
        identity = match.group(1)
        if identity.startswith('cite:'):
            return '[' + identity[5:] + ']'
        return validation['claim_ledger'][identity]['display']
    return TOKEN.sub(substitute, text)


def build_pdf(narrative, analysis, tables, verification, output, *, base_dir=None):
    """Actual authoring only after the external PDF-skill marker has succeeded.

    Dependencies are imported lazily.  A temporary PDF is retained on layout/text
    failure for diagnosis; the final artifact is installed only after five-page
    count and extraction checks.  Visual Poppler inspection remains mandatory.
    """
    validation = validate(narrative, analysis, tables, verification, base_dir=base_dir)
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_LEFT
    from reportlab.lib.pagesizes import letter
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import inch
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, PageBreak, Image, Table, TableStyle
    from pypdf import PdfReader
    output = Path(output).resolve()
    if output.exists():
        raise FileExistsError('Preserve the existing paper; author a new reviewed version')
    temp_dir = Path(base_dir or '.') / 'tmp/pdfs'
    temp_dir.mkdir(parents=True, exist_ok=True)
    handle, temporary = tempfile.mkstemp(prefix='decision-context-benchmark-', suffix='.pdf', dir=temp_dir)
    os.close(handle)
    page_width, page_height = letter
    margin = .65 * inch
    text_width = page_width - 2 * margin
    styles = {
        'title': ParagraphStyle('PaperTitle', fontName='Helvetica-Bold', fontSize=17, leading=20, spaceAfter=10),
        'authors': ParagraphStyle('PaperAuthors', fontName='Helvetica', fontSize=9, leading=12, spaceAfter=10),
        'heading': ParagraphStyle('PaperHeading', fontName='Helvetica-Bold', fontSize=11.5, leading=14, spaceBefore=5, spaceAfter=8),
        'body': ParagraphStyle('PaperBody', fontName='Times-Roman', fontSize=10.3, leading=13.2, alignment=TA_LEFT, spaceAfter=7),
        'caption': ParagraphStyle('PaperCaption', fontName='Helvetica', fontSize=8.1, leading=10.5, spaceAfter=8),
        'table': ParagraphStyle('PaperTable', fontName='Helvetica', fontSize=8.2, leading=10.2),
        'reference': ParagraphStyle('PaperReference', fontName='Times-Roman', fontSize=8.4, leading=10.5, spaceAfter=5),
    }

    def paragraph(value, kind='body'):
        return Paragraph(escape(_render_text(value, narrative, validation)).replace('\n', '<br/>'), styles[kind])

    story = []
    for index, page in enumerate(narrative['pages']):
        if index:
            story.append(PageBreak())
        else:
            story.append(paragraph(narrative['title'], 'title'))
            if narrative.get('authors'):
                story.append(paragraph(narrative['authors'], 'authors'))
        story.append(paragraph(page['heading'], 'heading'))
        if page['role'] == 'data_and_methods':
            story.append(paragraph('Labels are agent-reviewed source agreement, not human gold. BrowseSafe++ uses privacy-rewritten training-release material. NVIDIA is synthetic and success-selected; benign controls are local injection deletions. The study measures static detection and scope diagnostics, not agent prevention.', 'caption'))
        for block in page['blocks']:
            kind = block['type']
            if kind in ('paragraph', 'heading'):
                story.append(paragraph(block['text'], 'body' if kind == 'paragraph' else 'heading'))
            elif kind == 'figure':
                artifact = validation['figures'][block['figure']]
                image = Image(artifact['path'])
                scale = min(text_width / image.imageWidth, 3.15 * inch / image.imageHeight)
                image.drawWidth = image.imageWidth * scale
                image.drawHeight = image.imageHeight * scale
                story.extend([image, Spacer(1, 4), paragraph(block['caption'], 'caption')])
            elif kind == 'table':
                rows = [[paragraph(value, 'table') for value in row] for row in block['rows']]
                table = Table(rows, colWidths=[text_width / len(rows[0])] * len(rows[0]), repeatRows=1)
                table.setStyle(TableStyle([('VALIGN', (0, 0), (-1, -1), 'TOP'),
                    ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#E9EDF0')),
                    ('LINEBELOW', (0, 0), (-1, 0), .6, colors.HexColor('#5F6B72')),
                    ('BOTTOMPADDING', (0, 0), (-1, -1), 5), ('TOPPADDING', (0, 0), (-1, -1), 5)]))
                story.extend([table, Spacer(1, 4), paragraph(block['caption'], 'caption')])
            else:
                for reference in narrative['references']:
                    if reference['id'] in validation['used_reference_ids']:
                        label = f"[{reference['id']}] {reference['authors']} ({reference['year']}). {reference['title']}."
                        url = escape(reference['url'], {'"': '&quot;'})
                        story.append(Paragraph(escape(label) + f' <link href="{url}" color="#245B83">Source</link>', styles['reference']))

    def footer(canvas, document):
        canvas.setTitle(_render_text(narrative['title'], narrative, validation))
        if narrative.get('authors'):
            canvas.setAuthor(narrative['authors'])
        canvas.setFont('Helvetica', 8)
        canvas.setFillColor(colors.HexColor('#46515A'))
        canvas.drawString(margin, .35 * inch, PROJECT)
        canvas.drawRightString(page_width - margin, .35 * inch, str(document.page))

    doc = SimpleDocTemplate(temporary, pagesize=letter, leftMargin=margin, rightMargin=margin,
        topMargin=.60 * inch, bottomMargin=.60 * inch, title=narrative['title'])
    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    reader = PdfReader(temporary)
    if len(reader.pages) != 5:
        raise ValueError('Paper layout overflowed the five authored pages; inspect temporary PDF: ' + temporary)
    extracted = '\n'.join(page.extract_text() or '' for page in reader.pages)
    if '{{' in extracted or PLACEHOLDER.search(extracted) or PROJECT not in extracted:
        raise ValueError('PDF extraction found unresolved content; inspect temporary PDF: ' + temporary)
    for page, authored in zip(reader.pages, narrative['pages']):
        heading = _render_text(authored['heading'], narrative, validation)
        if heading not in (page.extract_text() or ''):
            raise ValueError('Authored page heading missing or page boundaries changed: ' + temporary)
    output.parent.mkdir(parents=True, exist_ok=True)
    os.replace(temporary, output)
    validation.update(pdf_created=True, output_sha256=file_digest(output), output_path=str(output),
                      extracted_page_count=5, poppler_visual_review_required=True)
    return validation


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('narrative', 'analysis', 'tables', 'verification'):
        parser.add_argument('--' + name, required=True, type=Path)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    values = [json.loads(getattr(args, name).read_text()) for name in ('narrative', 'analysis', 'tables', 'verification')]
    base = Path(__file__).resolve().parents[2]
    if args.write:
        if args.output is None:
            parser.error('--write requires --output')
        sys.path.insert(0, str(base))
        from scripts.study_v6.freeze import verify
        verify('confirmation')
        result = build_pdf(*values, args.output, base_dir=base)
    else:
        result = validate(*values, base_dir=base)
    print(json.dumps({key: result[key] for key in ('version', 'page_count', 'pdf_created')}))


if __name__ == '__main__':
    main()
